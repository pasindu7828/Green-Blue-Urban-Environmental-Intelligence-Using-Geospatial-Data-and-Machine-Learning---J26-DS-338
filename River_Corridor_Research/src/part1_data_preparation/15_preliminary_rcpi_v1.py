"""Step 30B: screened, EXPLORATORY Kelani River RCPI prototype (2020 -> 2024).

Combines three planning-indicator domains on the 28 fixed 500m reaches:
  M: median ABSOLUTE apparent Sentinel-2 width difference (metres), NOT bank erosion;
  V: net apparent NDVI vegetation-cover decrease / common-valid land area;
  U: equal combination of current OSM building footprint (%) and road density.

Domain weights 1/3 each, an explicit proposal baseline / scenario assumption,
NOT expert-elicited weights. Jenks natural breaks are fitted ONLY on eligible
reaches. Incomplete/low-coverage reaches are UNSCORED, never filled with zero.
The result is NOT validated risk, legal encroachment, ground-truth morphology,
or a supervised ML prediction. Generated files have unique prefix 30_rcpi_/30_.

Inputs generated by Steps 27B, 28B and 29C. Use --root for integration tests.
"""
from __future__ import annotations

import argparse
import json
from datetime import datetime, timezone
from pathlib import Path

import geopandas as gpd
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib.patches import Patch
import numpy as np
import pandas as pd

YEAR_A, YEAR_B = 2020, 2024
ZONE = '0-100m'
MIN_MATCHED = 3
MIN_WIDTH_PCT = 50.0
MIN_LAND_PCT = 70.0
REACH_IDS = [f'R{i:03d}' for i in range(1, 29)]
N_CLASSES = 4
CLASS_NAMES = ['LOW', 'MEDIUM', 'HIGH', 'VERY_HIGH']
CLASS_COLORS = {'LOW': '#89c8ad', 'MEDIUM': '#f7d375', 'HIGH': '#ef9653',
                'VERY_HIGH': '#c94748', 'INSUFFICIENT_EVIDENCE': '#b8bfc6'}
SCENARIOS = {
    'equal_weight_baseline': (1/3, 1/3, 1/3),
    'morphology_emphasis': (0.50, 0.25, 0.25),
    'vegetation_emphasis': (0.25, 0.50, 0.25),
    'urban_emphasis': (0.25, 0.25, 0.50),
}


def require(df, cols, name):
    missing = set(cols) - set(df.columns)
    if missing:
        raise ValueError(f'{name} missing required columns: {sorted(missing)}')


def unique_28(df, name):
    if len(df) != 28 or df['reach_id'].duplicated().any() or set(df['reach_id']) != set(REACH_IDS):
        raise ValueError(f'{name}: expected one row for every reach R001--R028; got {len(df)} rows')


def percentile_score(series, name, reference_mask, audit):
    """Monotonic P05--P95 normalization; preserve missing, no hidden zero fill."""
    ref = pd.to_numeric(series[reference_mask], errors='coerce')
    if ref.isna().any() or not np.isfinite(ref.to_numpy()).all():
        raise ValueError(f'{name}: invalid numeric reference values')
    lo, hi = [float(v) for v in np.percentile(ref.to_numpy(), [5, 95])]
    if hi - lo <= 1e-9:
        raise ValueError(f'{name}: no discriminating variation for 5-95% normalization; inspect inputs')
    audit.append({'indicator': name, 'p05': lo, 'p95': hi,
                  'reference_reaches': int(reference_mask.sum()), 'direction': 'larger_means_more_pressure'})
    return ((pd.to_numeric(series, errors='coerce') - lo) / (hi - lo)).clip(0, 1)


def jenks_breaks(series, nclass=4):
    """Exact dynamic-programming 1D Jenks within-class variance minimization.
    Cuts cannot split identical numerical values across priority classes.
    """
    v = np.sort(np.asarray(series, dtype=float))
    n = len(v)
    if len(np.unique(v)) < nclass:
        raise ValueError(f'Jenks requires >= {nclass} unique eligible scores, only {len(np.unique(v))} present')
    prefix = np.r_[0.0, np.cumsum(v)]
    squares = np.r_[0.0, np.cumsum(v*v)]
    def sse(start, end):
        length = end - start
        total = prefix[end] - prefix[start]
        return max(0.0, float(squares[end] - squares[start] - total*total/length))
    dp = np.full((nclass+1, n+1), np.inf)
    prev = np.full((nclass+1, n+1), -1, dtype=int)
    dp[0, 0] = 0.0
    for k in range(1, nclass+1):
        for j in range(k, n+1):
            for i in range(k-1, j):
                if i > 0 and v[i-1] == v[i]:
                    continue
                cost = dp[k-1, i] + sse(i, j)
                if cost < dp[k, j]:
                    dp[k, j], prev[k, j] = cost, i
    if not np.isfinite(dp[nclass, n]):
        raise ValueError('Could not find Jenks partition without splitting identical scores')
    groups = []
    j = n
    for k in range(nclass, 0, -1):
        i = int(prev[k, j])
        groups.append((i, j))
        j = i
    groups.reverse()
    if groups[0][0] != 0 or groups[-1][1] != n:
        raise AssertionError('Jenks partition is incomplete')
    return [float(v[0])] + [float(v[j-1]) for i, j in groups]


def assign_classes(values, breaks):
    # Equality at upper edge remains in the preceding class.
    inner = np.asarray(breaks[1:-1])
    return [CLASS_NAMES[int(np.searchsorted(inner, float(x), side='left'))] for x in values]


def load_and_join(root):
    report = root / 'outputs/reports'
    widths = pd.read_csv(report / '27_s2_transect_width_change_pairs.csv')
    annual = pd.read_csv(report / '27_s2_transect_widths_2018_2025.csv')
    veg = pd.read_csv(report / '28_s2_riparian_change_by_reach.csv')
    urban = pd.read_csv(report / '29_osm_pressure_by_reach.csv')

    require(widths, ['year_a','year_b','transect_id','reach_id','qa_matched','apparent_width_delta_m'], 'Step27 pairs')
    require(annual, ['year','transect_id','reach_id'], 'Step27 annual widths')
    require(veg, ['year_a','year_b','zone','reach_id','matched_land_coverage_pct',
                  'matched_valid_land_pixels','vegetation_loss_ha','vegetation_gain_ha',
                  'median_ndvi_delta','qa_flags'], 'Step28 vegetation')
    require(urban, ['reach_id','zone','building_footprint_pct',
                    'road_density_km_per_km2'], 'Step29 OSM')

    u = urban.loc[urban['zone'] == ZONE].copy()
    unique_28(u, 'Step29 combined zone')
    v = veg.loc[(veg.year_a == YEAR_A) & (veg.year_b == YEAR_B) & (veg.zone == ZONE)].copy()
    unique_28(v, 'Step28 2020-2024 combined zone')
    v['matched_land_ha'] = pd.to_numeric(v['matched_valid_land_pixels'],errors='raise') * 0.01
    if (v['matched_land_ha'] <= 0).any():
        raise ValueError('Nonpositive matched land area')
    v['gross_loss_pct_of_matched_land'] = 100 * v['vegetation_loss_ha'] / v['matched_land_ha']
    v['net_loss_pct_of_matched_land'] = 100 * (
        v['vegetation_loss_ha'] - v['vegetation_gain_ha']).clip(lower=0) / v['matched_land_ha']
    v['net_vegetation_change_ha'] = v['vegetation_gain_ha'] - v['vegetation_loss_ha']
    if (v['gross_loss_pct_of_matched_land'] > 100.1).any() or (v['gross_loss_pct_of_matched_land'] < 0).any():
        raise ValueError('Vegetation loss exceeds matched land domain')

    observed = annual.loc[annual.year == YEAR_A]
    if observed['transect_id'].duplicated().any() or len(observed) != 271:
        raise ValueError('Step27 annual 2020 transect roster is not the expected 271 unique rows')
    roster = observed.groupby('reach_id').size().rename('total_transects').reset_index()
    unique_28(roster, 'Step27 transect roster')

    w = widths.loc[(widths.year_a == YEAR_A) & (widths.year_b == YEAR_B)].copy()
    if len(w) != 271 or w['transect_id'].duplicated().any():
        raise ValueError('Expected 271 distinct 2020-2024 width comparison records')
    w['qa_matched'] = pd.to_numeric(w['qa_matched'], errors='raise')
    if not w['qa_matched'].isin([0,1]).all():
        raise ValueError('Unexpected width qa_matched flag values')
    w = w.loc[w['qa_matched'] == 1].copy()
    w['apparent_width_delta_m'] = pd.to_numeric(w['apparent_width_delta_m'],errors='raise')
    if w['apparent_width_delta_m'].isna().any():
        raise ValueError('Matched width measurement unexpectedly missing')
    w['abs_width_delta_m'] = w['apparent_width_delta_m'].abs()
    morph = w.groupby('reach_id').agg(
        matched_transects=('transect_id','nunique'),
        median_abs_width_change_m=('abs_width_delta_m','median'),
        median_signed_width_change_m=('apparent_width_delta_m','median')).reset_index()

    result = u[['reach_id','zone_area_ha','building_features_intersecting',
                'building_footprint_pct','road_density_km_per_km2']].merge(
        v[['reach_id','matched_land_coverage_pct','matched_valid_land_pixels',
           'matched_land_ha','median_ndvi_delta','vegetation_loss_ha',
           'vegetation_gain_ha','net_vegetation_change_ha','gross_loss_pct_of_matched_land',
           'net_loss_pct_of_matched_land','qa_flags']],on='reach_id',how='left',validate='one_to_one').merge(
        roster,on='reach_id',how='left',validate='one_to_one').merge(
        morph,on='reach_id',how='left',validate='one_to_one').sort_values('reach_id').reset_index(drop=True)
    unique_28(result,'Joined indicators')
    result['width_match_pct'] = 100 * result['matched_transects'].fillna(0) / result['total_transects']
    result['matched_transects'] = result['matched_transects'].fillna(0).astype(int)
    result['morphology_observed'] = result['matched_transects'] > 0
    result['width_quality_pass'] = (result['matched_transects'] >= MIN_MATCHED) & (result['width_match_pct'] >= MIN_WIDTH_PCT)
    result['vegetation_quality_pass'] = result['matched_land_coverage_pct'] >= MIN_LAND_PCT
    result['vegetation_coverage_caution_below85'] = result['matched_land_coverage_pct'] < 85.0
    result['rcpi_eligible'] = result['width_quality_pass'] & result['vegetation_quality_pass']
    result['reason_not_scored'] = result.apply(lambda r: ';'.join(
        x for cond,x in [
            (r['matched_transects'] == 0, 'NO_MATCHED_WIDTH'),
            (0 < r['matched_transects'] < MIN_MATCHED, 'TOO_FEW_WIDTH_OBSERVATIONS'),
            (r['width_match_pct'] < MIN_WIDTH_PCT, 'LOW_WIDTH_MATCH_COVERAGE'),
            (not r['vegetation_quality_pass'], 'LOW_MATCHED_LAND_COVERAGE')]
        if cond), axis=1)
    return result


def verify_spatial(root, result):
    path = root/'data/processed/urban_pressure_v1/29_osm_urban_pressure_28_reaches.gpkg'
    spatial = gpd.read_file(path, layer='reach_pressure')
    require(spatial,['reach_id','building_footprint_pct','road_density_km_per_km2'],'Step29 spatial layer')
    unique_28(spatial,'Step29 spatial reach layer')
    if spatial.crs is None or spatial.crs.to_epsg() != 32644:
        raise ValueError('Expected mapped urban pressure in EPSG:32644')
    if spatial.geometry.isna().any() or spatial.geometry.is_empty.any() or not spatial.geometry.is_valid.all():
        raise ValueError('Missing or invalid reach polygons')
    check = spatial[['reach_id','building_footprint_pct','road_density_km_per_km2']].merge(
        result[['reach_id','building_footprint_pct','road_density_km_per_km2']],on='reach_id',
        suffixes=('_gis','_csv'),validate='one_to_one')
    for col in ['building_footprint_pct','road_density_km_per_km2']:
        if not np.allclose(check[f'{col}_gis'],check[f'{col}_csv'],rtol=0,atol=0.001):
            raise ValueError(f'CSV/GPKG mismatch: {col}')
    return spatial[['reach_id','geometry']].merge(result,on='reach_id',validate='one_to_one')


def score(result):
    eligible = result['rcpi_eligible']
    n = int(eligible.sum())
    if n < 8:
        raise ValueError(f'Only {n} eligible reaches; too few for defensible 4-class prototype. Review quality thresholds/data.')
    audit = []
    result['morphology_normalized'] = percentile_score(result['median_abs_width_change_m'],
                                               'median_abs_width_change_m', eligible, audit)
    result['vegetation_normalized'] = percentile_score(result['net_loss_pct_of_matched_land'],
                                               'net_loss_pct_of_matched_land', eligible, audit)
    result['urban_building_normalized'] = percentile_score(result['building_footprint_pct'],
                                               'building_footprint_pct', eligible, audit)
    result['urban_roads_normalized'] = percentile_score(result['road_density_km_per_km2'],
                                               'road_density_km_per_km2', eligible, audit)
    result['urban_normalized'] = (result['urban_building_normalized']+result['urban_roads_normalized'])/2
    for name, weights in SCENARIOS.items():
        m,v,u = weights
        scores = (m*result['morphology_normalized'] + v*result['vegetation_normalized'] +
                  u*result['urban_normalized'])
        # Only eligible three-domain scores are valid. Crucial: never treat absent width as 0.
        result[name] = scores.where(eligible, np.nan)
    breaks = jenks_breaks(result.loc[eligible,'equal_weight_baseline'])
    result['priority_class'] = 'INSUFFICIENT_EVIDENCE'
    result.loc[eligible,'priority_class'] = assign_classes(result.loc[eligible,'equal_weight_baseline'],breaks)
    result['priority_rank_eligible_only'] = result['equal_weight_baseline'].rank(ascending=False,method='min')
    result['interpretation'] = np.where(eligible,'EXPLORATORY_THREE_DOMAIN_SCREENED',
                                       'INSUFFICIENT_EVIDENCE_FOR_THREE_DOMAIN_RCPI')
    sensitivity = []
    ref = result.loc[eligible,'equal_weight_baseline'].rank(ascending=False,method='average')
    for name, weights in SCENARIOS.items():
        comparison = result.loc[eligible,name]
        b = jenks_breaks(comparison)
        category = pd.Series(assign_classes(comparison,b),index=comparison.index)
        changed = int((category != result.loc[eligible,'priority_class']).sum())
        sensitivity.append({'scenario':name,'morphology_weight':weights[0],
                            'vegetation_weight':weights[1],'urban_weight':weights[2],
                            'eligible_reaches':n, 'spearman_rank_correlation_vs_equal':round(float(
                                ref.corr(comparison.rank(ascending=False,method='average'),method='pearson')),4),
                            'priority_class_changed_vs_equal':changed,
                            'jenks_score_breaks':';'.join(f'{x:.5f}' for x in b)})
    return result,pd.DataFrame(audit),pd.DataFrame(sensitivity),breaks


def outputs(root, result, geo, norms, sensitivity, breaks):
    reports=root/'outputs/reports'; figures=root/'outputs/figures'; folder=root/'data/processed/rcpi_v1'
    reports.mkdir(parents=True,exist_ok=True); figures.mkdir(parents=True,exist_ok=True); folder.mkdir(parents=True,exist_ok=True)
    result.to_csv(reports/'30_rcpi_preliminary_all_reaches.csv',index=False)
    norms.to_csv(reports/'30_rcpi_normalization_parameters.csv',index=False)
    sensitivity.to_csv(reports/'30_rcpi_weight_sensitivity.csv',index=False)
    geo = geo[['reach_id','geometry']].merge(result,on='reach_id',validate='one_to_one')
    geo.to_file(folder/'30_preliminary_rcpi_28_reaches.gpkg',layer='preliminary_rcpi',driver='GPKG')

    metadata={
        'status':'PRELIMINARY_EXPLORATORY_NOT_VALIDATED_PLANNING_RISK',
        'created_utc':datetime.now(timezone.utc).isoformat(),
        'years':[YEAR_A,YEAR_B], 'fixed_zone':ZONE,'total_reaches':28,
        'screened_reaches':int(result.rcpi_eligible.sum()),
        'unscored_reaches':int((~result.rcpi_eligible).sum()),
        'qa_minimum':{'matched_width_transects':MIN_MATCHED,'width_match_pct':MIN_WIDTH_PCT,
                      'matched_vegetation_land_pct':MIN_LAND_PCT,
                      'vegetation_caution_if_below_pct':85.0,
                      'note':'Vegetation minimum is inherited from Step28 MIN_PAIR_COVERAGE_PCT=70. Width >=3 and >=50% are new prototype screening assumptions. None are scientifically validated acceptance criteria'},
        'indicator_domains':{
            'morphology':'median absolute apparent 2020->2024 Sentinel-2 width difference in metres; NO inferred erosion/deposition or physical bank movement',
            'vegetation':'max(0, loss_ha-gain_ha) / matched common-valid land hectares * 100; NDVI>=0.30 proxy, NOT confirmed vegetation removal',
            'urban':'mean of minmax-normalized static OSM building footprint coverage pct and mapped road length density'},
        'normalization':'each raw indicator P05/P95 on ONLY eligible reaches, linear clamp [0,1], direction high = more planning attention',
        'domain_weights':{'morphology':1/3,'vegetation':1/3,'urban':1/3},
        'weights_note':'Proposal equal-domain baseline, no expert elicitation. Three emphasis scenarios are analysis assumptions.',
        'classes':CLASS_NAMES,'classification':'4-class Jenks natural breaks on eligible equal-weight scores only',
        'jenks_baseline_score_breaks':breaks,
        'limitations':['Width-derived morphology sensitive to water stage, acquisition dates, mixed 10/20m inputs and mask disagreement',
          'Only 2020 to 2024 observations, not a historical erosion trend',
          'Missing and quality-limited reaches intentionally receive NO RCPI score/class',
          'Static OSM cannot establish urban development dates, causality, illegal encroachment or legal setbacks',
          'Vegetation threshold and mapped fixed 2020 water mask are proxies, not surveyed riparian boundaries',
          'Jenks classification and weight sensitivity do not validate ground-truth priority',
          'This RCPI is not an ML model and is not supported by supervised priority ground truth'],
        'inputs':{
          'morphology':'outputs/reports/27_s2_transect_width_change_pairs.csv',
          'morphology_roster':'outputs/reports/27_s2_transect_widths_2018_2025.csv',
          'vegetation':'outputs/reports/28_s2_riparian_change_by_reach.csv',
          'urban':'outputs/reports/29_osm_pressure_by_reach.csv',
          'spatial':'data/processed/urban_pressure_v1/29_osm_urban_pressure_28_reaches.gpkg'}}
    (reports/'30_rcpi_preliminary_metadata.json').write_text(json.dumps(metadata,indent=2),encoding='utf-8')

    # Map class colors + evidence-limited area. Do not render NA as low priority.
    fig, ax = plt.subplots(figsize=(12.5,5.0))
    for klass in CLASS_NAMES + ['INSUFFICIENT_EVIDENCE']:
        sub=geo.loc[geo.priority_class==klass]
        if len(sub):
            sub.plot(ax=ax,color=CLASS_COLORS[klass],edgecolor='white',linewidth=0.27)
    centre=root/'data/raw/boundaries/kelani_river_centreline.geojson'
    if centre.exists():
        line=gpd.read_file(centre)
        if line.crs is not None:
            line.to_crs(geo.crs).plot(ax=ax,color='#3383b8',linewidth=0.8)
    ax.set_title('Kelani River | Preliminary RCPI | 2020–2024\n'
                 'Only quality-screened 3-domain reaches are scored; grey = insufficient evidence',fontsize=12,weight='bold')
    ax.set_xlabel('Easting (m), EPSG:32644');ax.set_ylabel('Northing (m), EPSG:32644')
    ax.set_aspect('equal'); ax.ticklabel_format(style='plain',axis='both',useOffset=False)
    handles=[Patch(facecolor=CLASS_COLORS[k],label=k.replace('_',' ').title()) for k in CLASS_NAMES]
    handles.append(Patch(facecolor=CLASS_COLORS['INSUFFICIENT_EVIDENCE'],label='Insufficient evidence'))
    ax.legend(handles=handles,loc='lower left',frameon=True,ncol=2,fontsize=8)
    fig.text(0.5,.01,'Exploratory satellite/OSM indicator composite — NOT surveyed river erosion, legal encroachment or validated risk',
             ha='center',fontsize=8,color='#6b7280')
    fig.savefig(figures/'30_rcpi_preliminary_screened_map.png',dpi=170,bbox_inches='tight');plt.close(fig)

    fig,ax=plt.subplots(figsize=(12,5.2))
    ranked=result.loc[result.rcpi_eligible].sort_values('equal_weight_baseline',ascending=False)
    bars=ax.bar(ranked.reach_id,ranked.equal_weight_baseline,
                color=[CLASS_COLORS[c] for c in ranked.priority_class])
    ax.set_ylabel('Equal-weight exploratory RCPI (0–1)')
    ax.set_xlabel('Eligible reach');ax.set_ylim(0,1.05)
    ax.grid(axis='y',alpha=.15);ax.tick_params(axis='x',labelrotation=65)
    ax.set_title('Screened reaches only | Preliminary RCPI ranking | Unscored reaches intentionally excluded')
    fig.savefig(figures/'30_rcpi_preliminary_screened_ranking.png',dpi=170,bbox_inches='tight');plt.close(fig)
    print('\n========== STEP 30B | PRELIMINARY RCPI COMPLETE ==========')
    print('28 total reaches:',len(result))
    print('Quality-screened/eligible:',int(result.rcpi_eligible.sum()))
    print('Insufficient evidence/unscored:',int((~result.rcpi_eligible).sum()))
    print('Priority categories including unscored:\n'+result.priority_class.value_counts().to_string())
    print('Vegetation coverage <85% (caution, not automatic exclusion):', int(result.vegetation_coverage_caution_below85.sum()))
    print('\nReasons for unscored reaches:')
    print(result.loc[~result.rcpi_eligible,['reach_id','matched_transects','width_match_pct',
                            'matched_land_coverage_pct','reason_not_scored']].to_string(index=False))
    print('\nTop SCREENED priority candidates (not verified risk):')
    print(result.loc[result.rcpi_eligible].nlargest(8,'equal_weight_baseline')[[
         'reach_id','equal_weight_baseline','priority_class','matched_transects',
         'width_match_pct','net_vegetation_change_ha','building_footprint_pct']].to_string(index=False))
    print('\nSensitivity (relative to equal baseline):')
    print(sensitivity[['scenario','spearman_rank_correlation_vs_equal','priority_class_changed_vs_equal']].to_string(index=False))
    print('\nCSV:',reports/'30_rcpi_preliminary_all_reaches.csv')
    print('GeoPackage:',folder/'30_preliminary_rcpi_28_reaches.gpkg')
    print('Map:',figures/'30_rcpi_preliminary_screened_map.png')
    print('Ranking:',figures/'30_rcpi_preliminary_screened_ranking.png')
    print('WARNING: Experimental index and analyst-selected QA gates; not independently validated risk.')


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--root',type=Path,default=Path(__file__).resolve().parents[2],
                        help='River_Corridor_Research directory (optional for testing)')
    args=parser.parse_args()
    root=args.root.resolve()
    print('========== STEP 30B | EXPLORATORY QUALITY-GATED RCPI ==========')
    result=load_and_join(root)
    geo=verify_spatial(root,result)
    result,norms,sensitivity,breaks=score(result)
    outputs(root,result,geo,norms,sensitivity,breaks)


if __name__=='__main__':
    main()
